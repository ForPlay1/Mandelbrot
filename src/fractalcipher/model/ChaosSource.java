package fractalcipher.model;

import java.util.Map;

/**
 * Общий контракт и для фракталов (Мандельброт, Жюлиа, ...),
 * и для хаотических карт (логистическая, Хенона, ...).
 * Каждая реализация умеет одно: по параметрам породить
 * псевдослучайную последовательность заданной длины,
 * которая дальше используется для шифрования изображения
 * (как маска для XOR, как перестановка пикселей и т.д.).
 */
public interface ChaosSource {

    /**
     * @param length  сколько значений нужно (например, ширина*высота*каналы)
     * @param params  параметры конкретного источника (r, c, x0, ... — свои для каждого)
     */
    double[] generate(int length, Map<String, Double> params);

    /** Имя источника для реестра/выбора пользователем, например "mandelbrot", "logistic" */
    String getName();
}