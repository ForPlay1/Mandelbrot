package fractalcipher.model.permutation;

import java.util.Map;

/**
 * Контракт для любого источника перестановки (confusion-часть шифра).
 * <p>
 * Реализация не обязана быть фракталом в узком смысле — важно только,
 * чтобы на выходе получался корректный массив индексов пикселей.
 * </p>
 */
public interface PermutationSource {

    /**
     * Генерирует перестановку индексов пикселей.
     *
     * @param length Общее количество пикселей в изображении (ширина × высота).
     * @param params Параметры конкретного фрактала (свои для каждого),
     *               сюда же всегда добавляются "width" и "height",
     *               чтобы источник знал форму изображения.
     * @return Массив {@code int[]} длиной {@code length}, где
     *         {@code result[новая_позиция] = исходный_индекс_пикселя}.
     */
    int[] generatePermutation(int length, Map<String, Double> params);

    /**
     * Возвращает имя источника для регистрации в фабрике и выбора в UI.
     *
     * @return Уникальное строковое имя (например, "mandelbrot").
     */
    String getName();
}