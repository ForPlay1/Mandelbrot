package fractalcipher.domain;

/**
 * Режим шифрования — определяет, какие этапы (перестановка, диффузия, CBC)
 * применять.
 * <p>
 * Используется в научных экспериментах для оценки вклада каждого этапа
 * в общую криптостойкость. Значение по умолчанию — {@link #FULL}.
 * </p>
 *
 * @author FractalCipher Team
 * @see FractalChaosCipher
 */
public enum EncryptionMode {
    /**
     * Только перестановка.
     * <p>Диффузия заменяется XOR с нулевым потоком, CBC выключен.</p>
     */
    PERMUTATION_ONLY,

    /**
     * Только диффузия.
     * <p>Перестановка — тождественная (identity), CBC выключен.</p>
     */
    DIFFUSION_ONLY,

    /**
     * Полная схема: перестановка + диффузия + два прохода CBC с S-боксами.
     * <p>Используется в реальном шифровании.</p>
     */
    FULL
}