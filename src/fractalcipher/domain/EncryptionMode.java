package fractalcipher.domain;

/**
 * Режим шифрования — определяет, какие этапы применять.
 * Нужен для научного сравнения вклада каждого этапа.
 */
public enum EncryptionMode {
    /** Только перестановка. Диффузия = XOR с нулевым потоком. CBC выключен. */
    PERMUTATION_ONLY,

    /** Только диффузия. Перестановка = identity. CBC выключен. */
    DIFFUSION_ONLY,

    /** Полная схема: перестановка + диффузия + CBC с S-боксами. */
    FULL
}